export type BaseStyle =
  | "war-room"
  | "outreach-hq"
  | "intel-room"
  | "content-lab"
  | "comms-tower"
  | "barracks";

export interface ProjectBase {
  projectId: string; // acts as buildingId
  name: string;
  style: BaseStyle;
  x: number;
  y: number;
  width: number;
  height: number;
  status: "active" | "idle" | "error";
  palette: string[];
  frames: number[][][]; // pixel art frames [frame][row][col]
  agentDockPoints: Array<{ x: number; y: number }>;
}

export interface Decoration {
  id: string;
  x: number;
  y: number;
  width: number;
  height: number;
  palette: string[];
  frames: number[][][];
}

export interface MapConfig {
  width: number;
  height: number;
  tileSize: number;
  bases: ProjectBase[];
  decorations: Decoration[];
  homePosition: { x: number; y: number };
  paths: Array<{
    from: string;
    to: string;
    waypoints: Array<{ x: number; y: number }>;
  }>;
}

