// ---------------------------------------------------------------------------
// map-data.ts -- War Room pixel-art map configuration
// 30x20 tile grid  (480x320 native pixels, 16px per tile)
// ---------------------------------------------------------------------------

export type BaseStyle =
  | "comms-tower"
  | "server-rack"
  | "beacon-tower"
  | "forge-station";

export interface ProjectBase {
  projectId: string;
  name: string;
  style: BaseStyle;
  x: number; // grid position in tiles (16px each)
  y: number;
  width: number; // building width in pixels
  height: number; // building height in pixels
  status: "active" | "idle" | "error";
  palette: string[];
  frames: number[][][]; // pixel art frames [frame][row][col]
  agentDockPoints: Array<{ x: number; y: number }>; // where agents stand
}

export interface MapConfig {
  width: number; // in tiles
  height: number;
  tileSize: number; // 16
  bases: ProjectBase[];
  homePosition: { x: number; y: number }; // idle-agent rally point (px)
  paths: Array<{
    from: string;
    to: string;
    waypoints: Array<{ x: number; y: number }>;
  }>;
}

